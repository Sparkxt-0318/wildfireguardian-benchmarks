"""Shared helpers for the benchmark authoring scripts.

Every benchmark in this repository is written by one of the ``author_*.py``
scripts in this directory.  The scripts are the *design artefact*: they hold the
hand-derived expected values, and they can be re-run at any time to regenerate
``benchmarks/`` byte for byte.

The critical rule, stated here because this is where it is easiest to break:

    **Expected values are authored by hand in these scripts.  They are never
    copied out of a solver run.**

If a solver disagrees with an authored value, exactly one of the two is wrong
and someone has to work out which.  That is the entire point of the suite.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from wg_benchmarks import yamlio  # noqa: E402  (path shim must come first)

BANNER = "# GENERATED by tools/authoring/{script}. Edit the script, not this file.\n"


def write_benchmark(
    directory: str,
    meta: dict,
    inputs: dict[str, dict],
    expected: dict,
    readme: str,
    script: str,
) -> Path:
    """Write one complete benchmark directory."""
    path = REPO_ROOT / directory
    (path / "inputs").mkdir(parents=True, exist_ok=True)
    (path / "expected").mkdir(parents=True, exist_ok=True)
    (path / "figures").mkdir(parents=True, exist_ok=True)

    banner = BANNER.format(script=script)
    meta = dict(meta)
    meta["inputs"] = {name: f"inputs/{name}.yaml" for name in inputs}

    (path / "benchmark.yaml").write_text(banner + yamlio.dumps(meta), encoding="utf-8")
    for name, document in inputs.items():
        (path / "inputs" / f"{name}.yaml").write_text(
            banner + yamlio.dumps(document), encoding="utf-8"
        )
    (path / "expected" / "expected.yaml").write_text(
        banner + yamlio.dumps(expected), encoding="utf-8"
    )
    (path / "README.md").write_text(readme.strip() + "\n", encoding="utf-8")
    keep = path / "figures" / ".gitkeep"
    if not any(p for p in (path / "figures").iterdir() if p.name != ".gitkeep"):
        keep.touch()
    return path


def report(paths: list[Path]) -> None:
    for path in paths:
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    print(f"{len(paths)} benchmark(s)")
